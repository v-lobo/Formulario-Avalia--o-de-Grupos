-- 1. Tabela de Avaliações (Sessão do Grupo)
CREATE TABLE evaluations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  leader_name TEXT NOT NULL,
  unit TEXT NOT NULL,
  grade TEXT NOT NULL,
  class TEXT NOT NULL,
  group_number INTEGER NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabela de Avaliações dos Integrantes
CREATE TABLE member_evaluations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id BIGINT REFERENCES evaluations(id) ON DELETE CASCADE,
  member_name TEXT NOT NULL,
  responsabilidade INTEGER NOT NULL,
  responsabilidade_obs TEXT DEFAULT '',
  relacionamento INTEGER NOT NULL,
  relacionamento_obs TEXT DEFAULT '',
  cooperacao INTEGER NOT NULL,
  cooperacao_obs TEXT DEFAULT '',
  organizacao INTEGER NOT NULL,
  organizacao_obs TEXT DEFAULT '',
  educacao INTEGER NOT NULL,
  educacao_obs TEXT DEFAULT ''
);

-- 3. Tabela de Avaliação do Líder
CREATE TABLE leader_evaluations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id BIGINT REFERENCES evaluations(id) ON DELETE CASCADE,
  responsabilidade INTEGER NOT NULL,
  responsabilidade_obs TEXT DEFAULT '',
  espirito_equipe INTEGER NOT NULL,
  espirito_equipe_obs TEXT DEFAULT '',
  orientacao_professor INTEGER NOT NULL,
  orientacao_professor_obs TEXT DEFAULT '',
  iniciativa INTEGER NOT NULL,
  iniciativa_obs TEXT DEFAULT '',
  educacao INTEGER NOT NULL,
  educacao_obs TEXT DEFAULT ''
);
